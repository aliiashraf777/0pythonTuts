# -----------------
# Python Operators
# -----------------

# 1. Arithmetic Operators - perform mathematial operations
# Addition (+) => 10+5=15
# Subtraction (-) => 10-5=5
# Multiplication (*) => 10*5=50
# Division (/) => 10/3=3.3
# Floor Division (//) => 10//3=3
# Modulus (%) => 20%6 = 2 remaining
# Exponential (**) => 2**2=4 > 2*2*2 = 4

# 2. Comparison (Relational) Operators
# Equal to (==) => 5==5 -> true
# Not equal to (!=) => 5!=3 -> true
# Greater than (>) => 5>2 -> true
# Less than (<) => 5<2 -> false
# Greater or equal (>=) => 5>=5 -> true
# Less or equal (<=) 5<=6 -> true

# 3. Assignments Operators - Assign and update
# Assign (=) => x=5 (assign 5 to x)
# += => x+=1 (x=x+1)
# -= => x-=1 (x=x-1)
# *= => x*=1 (x=x*1)
# /= => x/=1 (x=x/1)
# //= => x//=1 (x=x//1)
# %= => x%=1 (x=x%1)
# **= => x**=1 (x=x**1)

# 4. Logical Operators - Cobine conditional statements
# and => True if both are true
# x=10 and y>=x
# or => true if one is true
# x=10 or y<=x
# not => Reverses the result 
# print(not 1==1) (reverses true to false)

# 5. Identity Operators
# is => true if same object -> a is b
# x=[1,2]
# y=x
# z=[1,2]
# print(x is y) #true
# print(x is z) #false - both have diff address
# print(x is not z) #true

# 6. Membership Operators
# in => true if value exists -> a in b
# not in => true if values does not exist 
# mylist=[1,2,3]
# print(2 in mylist) #true
# print(5 not in mylist) #true